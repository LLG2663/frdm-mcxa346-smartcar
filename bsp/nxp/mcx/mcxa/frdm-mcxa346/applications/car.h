/* 上电把两轮目标清成 0 并刹车。
 *
 * 【谁先跑都安全】motor.c 的 motor_hw_init() 也是 INIT_APP_EXPORT，两个
 * INIT_APP_EXPORT 之间的先后顺序由链接顺序决定，这里不假设。
 *   - 若 Car_Init() 先跑：motor_set_duty() 对 motor1_pwm==RT_NULL 有守卫，
 *     是空操作；motor_set_direction() 只是写 GPIO 输出锁存，此时引脚还没被
 *     rt_pin_mode() 设成输出，写进去不驱动任何电平。随后 motor_hw_init()
 *     会把方向和占空比重新设成同样的状态。
 *   - 若 motor_hw_init() 先跑：这里就是幂等的再刹车一次。
 * 无论如何上电终态都是「两轮刹车、目标 0」。 */
void Car_Init(void);

/* 底层原语：带符号差速，上面所有动作函数都是它的封装。
 *   speed_left / speed_right: 正 = 前进，负 = 后退，0 = 该轮停。
 * 直接调它可以做任意差速（例如把角度环的输出接进来当执行器）。 */
void Car_Drive(rt_int16_t speed_left, rt_int16_t speed_right);

/* 带航向的直行：两轮同速前进，同时把航向外环的基准定成 target_yaw（度）。
 * 和上面五个动作的区别只在「基准从哪来」—— 那五个是"车现在指哪就保持哪"，
 * 这个是指定一个绝对朝向。航点跟随（follow.c）用它在航段里保持方位。
 *
 * target_yaw 用 jy901s 的 yaw 刻度（左负右正，见 jy901s.h），不是数学上的
 * 逆时针为正。基准变化超过 0.5 度视为换段，积分会清零。
 *
 * 【只有它能设定基准】别的动作（Car_Forward / 遥控 W）下一拍就会被
 * Car_StraightTick() 第 4 步重新锁成"当前朝向"，所以不跟随的时候它没有副作用。 */
void Car_DriveHeading(rt_int16_t speed, float target_yaw);

/* 目标方位的角速度（度/秒），作为航向外环的前馈。配合 Car_DriveHeading()
 * 用于"基准正在连续变化"的缓弯：每拍把目标相对上一拍的变化率填进来，
 * 外环就不必靠误差去追。只在两轮同速的直行动作下生效 —— 一旦换成差速、
 * 原地转或刹停，Car_StraightTick() 会自己清零。 */
void Car_SetHeadingRate(float deg_per_s);

/* ---- 五个基本动作 ----
 * 参数是期望速度，会被钳到 ±CAR_SPEED_MAX。 */
void Car_Forward(rt_uint16_t speed);        /* 前进：两轮同速正转 */
void Car_Backward(rt_uint16_t speed);       /* 后退：两轮同速反转 */

/* 弧线转弯：两轮都正转，内侧轮减速。speed 给默认档（400）就行 —— 外侧至少要有
 * 2 个编码器计数（48）才做得出弧线，否则退回成绕内侧轮原地转。 */
void Car_TurnLeft(rt_uint16_t speed);       /* 左转（弧线）：左轮=内侧减速 */
void Car_TurnRight(rt_uint16_t speed);      /* 右转（弧线）：右轮=内侧减速 */

void Car_SpinLeft(rt_uint16_t speed);       /* 自转左（原地，逆时针）：左轮后退、右轮前进 */
void Car_SpinRight(rt_uint16_t speed);      /* 自转右（原位，顺时针）：左轮前进、右轮后退 */

/* ---- 停止 ---- */
/* 两轮刹停并保持。立刻生效，不等 PID 下一次迭代（见 car.c 里的说明）。 */
void Car_Brake(void);

/* ---- 遥控速度旋钮（msh 的 `bt speed` 用它，不用重新编译就能整定） ---- */
rt_uint16_t Car_GetRunSpeed(void);
void        Car_SetRunSpeed(rt_uint16_t speed);

/* ---- 直行辅助开关（代码用；msh 上还是 `head on|off`）----
 * follow.c 用它把原值存下来再还原，见 car.c 里的注释。 */
rt_bool_t Car_GetHeadOn(void);
void      Car_SetHeadOn(rt_bool_t on);

/* 丢掉航向基准（head_armed），下一拍重新按"当前朝向"锁。航点跟随放手时调。 */
void      Car_HeadRelease(void);

/* ---- 航向外环的运行期旋钮：msh 的 `head` 和无线串口上的 `#head` 是同一个入口 ----
 * argv 按 msh 的约定：argv[0] 是命令名 "head"，子命令从 argv[1] 起
 * （和 msh 的 cmd_head() 一样，所以那边是个三行包装）。
 *
 * 【为什么要开在无线串口上】这套旋钮只能"看着车"调，而车要落地跑、落地就得电池
 * 供电；msh 偏偏要插 USB，一插 USB 电机电源 VADJ 就从 7.49V 塌到 3.56V。
 * 结果就是 kp/ki/kd/sign/off 全处于「写了但没在车真正跑的时候用过」的状态。
 *
 * 【回包只在控制台上】内部是 rt_kprintf，从无线串口转进来时打给的是 uart2，
 * 那条链路上看不见 —— 无线串口侧只回一行 ok/err，数值从周期上报行的
 * tgt（= base ± corr）和 duty 里读，见 speed_report.h。
 * 失败返回负的 rt_err_t，成功返回 RT_EOK。 */
rt_err_t Car_CmdHead(int argc, char **argv);

#endif /* __CAR_H__ */
